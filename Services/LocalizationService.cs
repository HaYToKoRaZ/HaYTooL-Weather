namespace HaYTooLWeather.Services;

/// <summary>
/// 7 dilde (TR, EN, ES, DE, PT, AR, RU) dinamik yerelleştirme servisi.
/// </summary>
public static class LocalizationService
{
    public static string CurrentLanguage { get; private set; } = "tr";

    public static readonly Dictionary<string, string> SupportedLanguages = new()
    {
        { "tr", "Türkçe (Turkish)" },
        { "en", "English" },
        { "es", "Español (Spanish)" },
        { "de", "Deutsch (German)" },
        { "pt", "Português (Portuguese)" },
        { "ar", "العربية (Arabic)" },
        { "ru", "Русский (Russian)" }
    };

    public static void SetLanguage(string langCode)
    {
        if (SupportedLanguages.ContainsKey(langCode.ToLowerInvariant()))
        {
            CurrentLanguage = langCode.ToLowerInvariant();
        }
        else
        {
            CurrentLanguage = "tr";
        }
    }

    public static string Get(string key)
    {
        if (_translations.TryGetValue(CurrentLanguage, out var dict) && dict.TryGetValue(key, out var text))
            return text;

        if (_translations["en"].TryGetValue(key, out var fallbackText))
            return fallbackText;

        return key;
    }

    /// <summary>
    /// WMO Hava Durumu Koduna (0-99) göre mevcut dilde açıklama döner.
    /// </summary>
    public static string GetWeatherDescription(int code)
    {
        return code switch
        {
            0 => Get("w_clear_sky"),
            1 => Get("w_mainly_clear"),
            2 => Get("w_partly_cloudy"),
            3 => Get("w_overcast"),
            45 => Get("w_fog"),
            48 => Get("w_depositing_rime_fog"),
            51 => Get("w_drizzle_light"),
            53 => Get("w_drizzle_moderate"),
            55 => Get("w_drizzle_dense"),
            56 => Get("w_freezing_drizzle_light"),
            57 => Get("w_freezing_drizzle_dense"),
            61 => Get("w_rain_slight"),
            62 or 63 => Get("w_rain_moderate"),
            65 => Get("w_rain_heavy"),
            66 => Get("w_freezing_rain_light"),
            67 => Get("w_freezing_rain_heavy"),
            71 => Get("w_snow_slight"),
            73 => Get("w_snow_moderate"),
            75 => Get("w_snow_heavy"),
            77 => Get("w_snow_grains"),
            80 => Get("w_rain_showers_slight"),
            81 => Get("w_rain_showers_moderate"),
            82 => Get("w_rain_showers_violent"),
            85 => Get("w_snow_showers_slight"),
            86 => Get("w_snow_showers_heavy"),
            95 => Get("w_thunderstorm"),
            96 => Get("w_thunderstorm_slight_hail"),
            99 => Get("w_thunderstorm_heavy_hail"),
            _ => Get("w_unknown")
        };
    }

    public static string GetDayName(DayOfWeek dayOfWeek)
    {
        return dayOfWeek switch
        {
            DayOfWeek.Monday => Get("day_mon"),
            DayOfWeek.Tuesday => Get("day_tue"),
            DayOfWeek.Wednesday => Get("day_wed"),
            DayOfWeek.Thursday => Get("day_thu"),
            DayOfWeek.Friday => Get("day_fri"),
            DayOfWeek.Saturday => Get("day_sat"),
            DayOfWeek.Sunday => Get("day_sun"),
            _ => dayOfWeek.ToString()
        };
    }

